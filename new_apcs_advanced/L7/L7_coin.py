#
# 零錢兌換問題（Coin Change Problem）
# 核心演算法：貪婪演算法（Greedy Algorithm）
# 解題策略：由大到小優先選擇面額最大的硬幣，盡可能換取最少數量的硬幣
# 注意前提：輸入的幣值需已由小到大排序（例如：1 5 10 50），且幣值系統需符合標準貨幣規範
#

# 輸入所有可用的硬幣面額，並轉換為整數串列（預設由小到大，例如：1 5 10 50）
coins = list(map(int, input().split()))

# 輸入要兌換（或找零）的目標總金額
money = int(input())

# 累加器：記錄換得的總硬幣數量
num = 0

# 由大到小反向遍歷硬幣面額（從最後一個索引倒數至索引 0）
# 參數說明：range(起始索引, 結束條件, 步進值)
# len(coins)-1: 最後一個元素的索引（最大面額）
# -1: 走訪到索引 0 為止
# -1: 每次遞減 1
for i in range(len(coins) - 1, -1, -1):
    # 計算目前面額最多能換幾個（整數除法 //）並累加到總數量
    num = num + money // coins[i]
    
    # 取餘數（%）更新剩餘尚未兌換的金額
    money = money % coins[i]

# 輸出最少硬幣總數
print(num)